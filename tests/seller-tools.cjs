const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'), {url:'https://example.test/',runScripts:'outside-only'});
const w = dom.window;
w.eval(fs.readFileSync(path.join(root,'seller-tools.js'),'utf8'));
const $ = id => w.document.getElementById(id);
const form = $('cost-form');
const submit = values => {
  for (const [name,value] of Object.entries(values)) form.elements.namedItem(name).value = value;
  form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
};
assert($('cost-result').hidden);
submit({home:400000,rate:3,other:1000,direct:5000});
assert.equal($('cost-comparison-total').textContent,'$13,000.00');
assert.match($('cost-difference').textContent,/\$8,000.00 lower/);
submit({direct:15000});assert.match($('cost-difference').textContent,/\$2,000.00 higher/);
submit({direct:13000});assert.match($('cost-difference').textContent,/same entered cost/);
submit({rate:0,other:0,direct:0});assert.equal($('cost-comparison-total').textContent,'$0.00');
submit({rate:''});assert($('cost-result').hidden);assert($('cost-error').textContent);
submit({rate:101});assert($('cost-result').hidden);
submit({rate:3,direct:-1});assert($('cost-result').hidden);
submit({direct:5000});assert(!$('cost-result').hidden);
form.elements.home.dispatchEvent(new w.Event('input',{bubbles:true}));assert($('cost-result').hidden);
submit({home:400000.01,rate:3,direct:5000.01,other:0});assert.match($('cost-difference').textContent,/\$6,999.99 lower/);
form.reset();assert($('cost-result').hidden);assert.equal($('cost-error').textContent,'');
const ids=[...w.document.querySelectorAll('[id]')].map(el=>el.id);assert.equal(new Set(ids).size,ids.length);
for(const a of w.document.querySelectorAll('#seller-tools a[href^="#"],#how a[href^="#"]')) assert(w.document.getElementById(a.hash.slice(1)),a.hash);
assert.equal(w.document.querySelectorAll('#how ol > li').length,4);
assert(w.document.querySelector('#seller-tools [data-sell]'));
console.log('Seller tools passed: quotes, higher/lower/equal costs, zero, invalid inputs, rounding, stale results, reset, links and IDs.');
dom.window.close();
